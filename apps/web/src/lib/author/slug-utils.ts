/**
 * Convert a pack name into a URL-safe slug.
 *
 * Example: "React Fundamentals" -> "react-fundamentals"
 */
export function slugify(text: string): string {
  return text
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, '')
    .replace(/[\s_]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}
